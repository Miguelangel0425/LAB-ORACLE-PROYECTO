--  DDL for View VW_REPORTE_VENTAS_DETALLADO
--------------------------------------------------------


  CREATE OR REPLACE FORCE EDITIONABLE VIEW "PROYECTO_BD"."VW_REPORTE_VENTAS_DETALLADO" ("ID_VENTA", "FECHA_VENTA", "ID_CLIENTE", "CLIENTE", "ID_PRODUCTO", "PRODUCTO", "CANTIDAD", "PRECIO_UNITARIO", "SUBTOTAL", "TOTAL_VENTA") AS 
  SELECT v.ID_VENTA,
       v.FECHA_VENTA,
       c.ID_CLIENTE,
       c.NOMBRE || ' ' || c.APELLIDO   AS CLIENTE,
       p.ID_PRODUCTO,
       p.NOMBRE                        AS PRODUCTO,
       d.CANTIDAD,
       d.PRECIO_UNITARIO,
       d.SUBTOTAL,
       v.TOTAL                         AS TOTAL_VENTA
FROM VENTAS v
JOIN CLIENTES c        ON c.ID_CLIENTE  = v.ID_CLIENTE
JOIN DETALLE_VENTA d   ON d.ID_VENTA    = v.ID_VENTA
JOIN PRODUCTOS p       ON p.ID_PRODUCTO = d.ID_PRODUCTO;
