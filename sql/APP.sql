--  DDL for Procedure SP_LOGIN
--------------------------------------------------------

set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "PROYECTO_BD"."SP_LOGIN" (
    p_username     IN  VARCHAR2,
    p_password     IN  VARCHAR2,
    o_estado       OUT VARCHAR2,
    o_id_usuario   OUT NUMBER,
    o_nombre       OUT VARCHAR2
) AS
    v_hash          VARCHAR2(256);
    v_hash_input    VARCHAR2(256);
    v_activo        NUMBER;
    v_id            NUMBER;
    v_nombre        VARCHAR2(150);
BEGIN
    SELECT PASSWORD_HASH, ACTIVO, ID_USUARIO, NOMBRE_COMPLETO
      INTO v_hash, v_activo, v_id, v_nombre
      FROM USUARIOS
     WHERE UPPER(USERNAME) = UPPER(p_username);

    SELECT STANDARD_HASH(p_password, 'SHA256') INTO v_hash_input FROM DUAL;

    IF v_hash != v_hash_input THEN
        o_estado := 'CREDENCIALES_INVALIDAS';
        o_id_usuario := NULL;
        o_nombre := NULL;
    ELSIF v_activo = 0 THEN
        o_estado := 'INACTIVO';
        o_id_usuario := NULL;
        o_nombre := NULL;
    ELSE
        o_estado := 'OK';
        o_id_usuario := v_id;
        o_nombre := v_nombre;
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        o_estado := 'CREDENCIALES_INVALIDAS';
        o_id_usuario := NULL;
        o_nombre := NULL;
END SP_LOGIN;
